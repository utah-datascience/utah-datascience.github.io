#!/usr/bin/env python3
"""Generate a page per talk, and the calendar feed, from `_data/talks/*.toml`.

The TOML files are the source of truth. Everything this writes is generated and
should never be edited by hand:

    _talks/*.md   one Jekyll page per talk
    talks.ics     an iCalendar feed of every talk, served at /talks.ics

(GitHub Pages builds Jekyll in safe mode, so custom plugins are unavailable and
both have to be generated ahead of time and committed.)

Usage:
    python3 scripts/generate_talks.py            # (re)generate everything
    python3 scripts/generate_talks.py --check    # fail if the output is stale
"""

from __future__ import annotations

import argparse
import datetime as dt
import glob
import json
import os
import re
import sys
import tomllib
from zoneinfo import ZoneInfo

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_DIR = os.path.join(ROOT, "_data", "talks")
OUT_DIR = os.path.join(ROOT, "_talks")
ICS_PATH = os.path.join(ROOT, "talks.ics")
TZ = ZoneInfo("America/Denver")
CALENDAR_NAME = "Utah Data Science & AI Lecture Series"
CALENDAR_DESC = (
    "Talks in the Data Science & AI Lecture Series at the Utah Center for Data "
    "Science. Generated from the talk records at datascience.utah.edu/talks/."
)
BANNER = "<!-- Generated by scripts/generate_talks.py from _data/talks/%s -- do not edit. -->"

SPEAKER_FIELDS = ("name", "affiliation", "role", "website", "photo", "email", "bio")
TALK_FIELDS = (
    "series",
    "location",
    "room",
    "zoom",
    "slides",
    "recording",
    "paper",
    "canceled",
    "tags",
)


class TalkError(Exception):
    pass


def yaml_scalar(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return json.dumps(str(value), ensure_ascii=False)  # JSON strings are valid YAML


def yaml_block(data: dict, indent: int = 0) -> list[str]:
    lines = []
    pad = " " * indent
    for key, value in data.items():
        if value in ("", None, [], {}):
            continue
        if isinstance(value, list):
            if all(isinstance(item, dict) for item in value):
                lines.append(f"{pad}{key}:")
                for item in value:
                    inner = yaml_block(item, indent + 4)
                    if not inner:
                        continue
                    lines.append(f"{pad}  - " + inner[0].strip())
                    lines.extend(inner[1:])
            else:
                lines.append(f"{pad}{key}: [" + ", ".join(yaml_scalar(v) for v in value) + "]")
        else:
            lines.append(f"{pad}{key}: {yaml_scalar(value)}")
    return lines


def parse_time(value, field: str, source: str) -> dt.time | None:
    if value in (None, ""):
        return None
    if isinstance(value, dt.time):
        return value
    for fmt in ("%H:%M", "%H:%M:%S", "%I:%M %p", "%I%p"):
        try:
            return dt.datetime.strptime(str(value).strip().upper(), fmt.upper()).time()
        except ValueError:
            continue
    raise TalkError(f"{source}: could not parse {field} {value!r} (use e.g. \"13:30\")")


def load_talk(path: str) -> dict:
    source = os.path.basename(path)
    with open(path, "rb") as handle:
        try:
            raw = tomllib.load(handle)
        except tomllib.TOMLDecodeError as error:
            raise TalkError(f"{source}: invalid TOML ({error})") from error

    talk = raw.get("talk")
    if not isinstance(talk, dict):
        raise TalkError(f"{source}: missing a [talk] table")
    if not talk.get("title"):
        raise TalkError(f"{source}: [talk] needs a title")

    date = talk.get("date")
    if isinstance(date, dt.datetime):
        date = date.date()
    if not isinstance(date, dt.date):
        raise TalkError(f"{source}: [talk] needs a date (e.g. date = 2026-09-04)")

    speakers = raw.get("speakers") or []
    if not isinstance(speakers, list) or not speakers:
        raise TalkError(f"{source}: needs at least one [[speakers]] entry")
    for speaker in speakers:
        if not speaker.get("name"):
            raise TalkError(f"{source}: every [[speakers]] entry needs a name")

    start = parse_time(talk.get("start_time"), "start_time", source)
    end = parse_time(talk.get("end_time"), "end_time", source)
    starts_at = dt.datetime.combine(date, start or dt.time(13, 30), tzinfo=TZ)

    slug = talk.get("slug") or os.path.splitext(source)[0]
    # a page headed "TBA" helps nobody; name it after whoever gave the talk
    title = str(talk["title"]).strip()
    if re.fullmatch(r"(?i)tba|tbd", title):
        title = "Talk by " + ", ".join(speaker["name"] for speaker in speakers)
    front = {
        "layout": "talk",
        "title": title,
        "date": starts_at.strftime("%Y-%m-%d %H:%M:%S %z"),
        "permalink": f"/talks/{slug}/",
        "slug": slug,
    }
    if start:
        front["start_time"] = starts_at.strftime("%-I:%M %p")
    if end:
        front["end_time"] = dt.datetime.combine(date, end, tzinfo=TZ).strftime("%-I:%M %p")
    for field in TALK_FIELDS:
        if field in talk:
            front[field] = talk[field]
    front["speakers"] = [
        {field: speaker[field] for field in SPEAKER_FIELDS if speaker.get(field)}
        for speaker in speakers
    ]
    front["speaker_names"] = ", ".join(speaker["name"] for speaker in speakers)
    front["source_file"] = f"_data/talks/{source}"
    front["generated"] = True

    body = str(talk.get("abstract", "")).strip()
    return {
        "source": source,
        "slug": slug,
        "front": front,
        "body": body,
        "starts_at": starts_at,
        "ends_at": dt.datetime.combine(date, end, tzinfo=TZ) if end else None,
        "speakers": speakers,
    }


def render(talk: dict) -> str:
    lines = ["---"]
    lines += yaml_block(talk["front"])
    lines += ["---", "", BANNER % talk["source"], ""]
    if talk["body"]:
        # abstracts are prose, so protect any accidental Liquid from the build
        if "{{" in talk["body"] or "{%" in talk["body"]:
            lines += ["{% raw %}", talk["body"], "{% endraw %}", ""]
        else:
            lines += [talk["body"], ""]
    return "\n".join(lines)



