def site_url() -> str:
    """The site's own address, taken from CNAME so the two cannot disagree."""
    cname = os.path.join(ROOT, "CNAME")
    if os.path.exists(cname):
        host = open(cname, encoding="utf-8").read().strip()
        if host:
            return f"https://{host}"
    return "https://utah-datascience.github.io"


def ics_escape(value: str) -> str:
    return (
        str(value)
        .replace("\\", "\\\\")
        .replace(";", "\\;")
        .replace(",", "\\,")
        .replace("\r\n", "\\n")
        .replace("\n", "\\n")
    )


def ics_fold(line: str) -> list[str]:
    """RFC 5545 says content lines are folded at 75 octets, continued with a space."""
    raw = line.encode("utf-8")
    if len(raw) <= 75:
        return [line]
    chunks, start = [], 0
    limit = 75
    while start < len(raw):
        end = min(start + limit, len(raw))
        while end < len(raw) and (raw[end] & 0xC0) == 0x80:  # never split a character
            end -= 1
        chunks.append(raw[start:end].decode("utf-8"))
        start = end
        limit = 74  # continuation lines carry a leading space
    return [chunks[0]] + [" " + chunk for chunk in chunks[1:]]


def ics_stamp(moment: dt.datetime) -> str:
    return moment.astimezone(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def ics_local(moment: dt.datetime) -> str:
    return moment.strftime("%Y%m%dT%H%M%S")


def event_description(talk: dict) -> str:
    front = talk["front"]
    parts = []
    who = []
    for speaker in talk["speakers"]:
        name = speaker["name"]
        if speaker.get("affiliation"):
            name += f' ({speaker["affiliation"]})'
        who.append(name)
    if who:
        parts.append(", ".join(who))
    if talk["body"]:
        parts.append(talk["body"])
    for label, field in (("Slides", "slides"), ("Recording", "recording")):
        if front.get(field):
            parts.append(f'{label}: {front[field]}')
    parts.append(f'{site_url()}{front["permalink"]}')
    return "\n\n".join(parts)


def build_ics(talks: list[dict]) -> str:
    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//Utah Center for Data Science//Talks//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        f"X-WR-CALNAME:{ics_escape(CALENDAR_NAME)}",
        f"X-WR-CALDESC:{ics_escape(CALENDAR_DESC)}",
        "X-WR-TIMEZONE:America/Denver",
        # a hint to subscribers about how often to re-read the feed; Apple and
        # Outlook honour it, Google refreshes on its own schedule regardless
        "REFRESH-INTERVAL;VALUE=DURATION:PT1H",
        "X-PUBLISHED-TTL:PT1H",
        # Mountain Time, so the feed is correct for subscribers in any timezone
        "BEGIN:VTIMEZONE",
        "TZID:America/Denver",
        "BEGIN:DAYLIGHT",
        "TZOFFSETFROM:-0700",
        "TZOFFSETTO:-0600",
        "TZNAME:MDT",
        "DTSTART:19700308T020000",
        "RRULE:FREQ=YEARLY;BYMONTH=3;BYDAY=2SU",
        "END:DAYLIGHT",
        "BEGIN:STANDARD",
        "TZOFFSETFROM:-0600",
        "TZOFFSETTO:-0700",
        "TZNAME:MST",
        "DTSTART:19701101T020000",
        "RRULE:FREQ=YEARLY;BYMONTH=11;BYDAY=1SU",
        "END:STANDARD",
        "END:VTIMEZONE",
    ]

    for talk in sorted(talks, key=lambda item: item["starts_at"]):
        front = talk["front"]
        starts = talk["starts_at"]
        ends = talk["ends_at"] or (starts + dt.timedelta(hours=1))
        summary = front["title"]
        if front.get("speaker_names"):
            summary += f' - {front["speaker_names"]}'
        lines += [
            "BEGIN:VEVENT",
            f'UID:{talk["slug"]}@{site_url().split("://")[1]}',
            # deliberately derived from the event, not from "now", so that
            # regenerating an unchanged record produces an unchanged file
            f"DTSTAMP:{ics_stamp(starts)}",
            f"DTSTART;TZID=America/Denver:{ics_local(starts)}",
            f"DTEND;TZID=America/Denver:{ics_local(ends)}",
            f"SUMMARY:{ics_escape(summary)}",
            f"DESCRIPTION:{ics_escape(event_description(talk))}",
            f'URL:{site_url()}{front["permalink"]}',
            "SEQUENCE:0",
            f'STATUS:{"CANCELLED" if front.get("canceled") else "CONFIRMED"}',
            "TRANSP:OPAQUE",
        ]
        location = front.get("location") or ""
        if front.get("zoom"):
            location = f'{location} | {front["zoom"]}' if location else front["zoom"]
        if location:
            lines.append(f"LOCATION:{ics_escape(location)}")
        if front.get("tags"):
            lines.append(f'CATEGORIES:{",".join(ics_escape(tag) for tag in front["tags"])}')
        lines.append("END:VEVENT")

    lines.append("END:VCALENDAR")

    folded = []
    for line in lines:
        folded.extend(ics_fold(line))
    return "\r\n".join(folded) + "\r\n"


def read_text(path: str) -> str:
    with open(path, encoding="utf-8", newline="") as handle:
        return handle.read()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write anything; exit non-zero if pages are out of date",
    )
    args = parser.parse_args()

    os.makedirs(OUT_DIR, exist_ok=True)
    sources = sorted(
        path
        for path in glob.glob(os.path.join(DATA_DIR, "*.toml"))
        if not os.path.basename(path).startswith("_")
    )

    pages, errors, seen, records = {}, [], {}, []
    for path in sources:
        try:
            talk = load_talk(path)
        except TalkError as error:
            errors.append(str(error))
            continue
        if talk["slug"] in seen:
            errors.append(
                f'{talk["source"]}: duplicate talk slug "{talk["slug"]}" '
                f'(also used by {seen[talk["slug"]]})'
            )
            continue
        seen[talk["slug"]] = talk["source"]
        records.append(talk)
        pages[os.path.join(OUT_DIR, f'{os.path.splitext(talk["source"])[0]}.md')] = render(talk)

    if errors:
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        return 1

    pages[ICS_PATH] = build_ics(records)

    existing = set(glob.glob(os.path.join(OUT_DIR, "*.md")))
    stale = sorted(existing - set(pages))
    changed = sorted(
        path
        for path, content in pages.items()
        if not os.path.exists(path) or read_text(path) != content
    )

    if args.check:
        if changed or stale:
            for path in changed:
                print(f"out of date: {os.path.relpath(path, ROOT)}", file=sys.stderr)
            for path in stale:
                print(f"orphaned:    {os.path.relpath(path, ROOT)}", file=sys.stderr)
            print(
                "\nRun `make talks` (or python3 scripts/generate_talks.py) and commit the result.",
                file=sys.stderr,
            )
            return 1
        print(f"{len(records)} talk page(s) and talks.ics up to date")
        return 0

    for path in changed:
        # newline="" keeps the CRLF line endings the iCalendar feed needs
        with open(path, "w", encoding="utf-8", newline="") as handle:
            handle.write(pages[path])
    for path in stale:
        os.remove(path)

    print(
        f"{len(records)} talk page(s) in {os.path.relpath(OUT_DIR, ROOT)}/ plus "
        f"talks.ics ({len(changed)} written, {len(stale)} removed)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
